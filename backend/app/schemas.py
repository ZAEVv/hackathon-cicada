# --- Request-side input hardening -------------------------------------------
# Client-supplied text is rejected (never stripped/normalised) so that what is
# hashed and stored is exactly what was validated. Forbidden: C0 controls (incl.
# NUL), DEL, C1 controls, U+2028/U+2029, bidi embeddings/overrides/isolates and
# lone surrogates. Only multiline fields may contain \t and \n.
_BASE_FORBIDDEN = "\x7f-\x9f\u2028\u2029\u202a-\u202e\u2066-\u2069\ud800-\udfff"
_FORBIDDEN_SINGLE_LINE = re.compile(f"[\x00-\x1f{_BASE_FORBIDDEN}]")
_FORBIDDEN_MULTILINE = re.compile(f"[\x00-\x08\x0b-\x1f{_BASE_FORBIDDEN}]")


def _reject(pattern: re.Pattern[str]):
    def check(value: str) -> str:
        match = pattern.search(value)
        if match:
            raise PydanticCustomError(
                "forbidden_character", "Text contains forbidden character U+{codepoint} at position {position}",
                {"codepoint": f"{ord(match.group()):04X}", "position": match.start()})
        return value
    return check


def _text(max_length: int, *, multiline: bool = False):
    pattern = _FORBIDDEN_MULTILINE if multiline else _FORBIDDEN_SINGLE_LINE
    return Annotated[str, StringConstraints(max_length=max_length), AfterValidator(_reject(pattern))]


# Numbers: finite, bounded, and strict (JSON numbers only; ints accepted, bools
# and numeric strings rejected).
MassKg = Annotated[float, Field(strict=True, allow_inf_nan=False, gt=0, le=1_000_000)]
ValueUsd = Annotated[float, Field(strict=True, allow_inf_nan=False, gt=0, le=1_000_000_000_000)]

# Identifiers for main.py path/header parameters (wired by the API layer).
ShipmentId = Annotated[str, StringConstraints(min_length=1, max_length=64, pattern=r"^[A-Za-z0-9_-]+$")]
IdempotencyKey = Annotated[str, StringConstraints(min_length=1, max_length=128, pattern=r"^[A-Za-z0-9._:~-]+$")]
# Route ids are generated by routing.py as "<service>@<ISO time>+..." or "unavailable:<service>+...".
RouteId = Annotated[str, StringConstraints(min_length=1, max_length=128, pattern=r"^[A-Za-z0-9_.:@+-]+$")]


